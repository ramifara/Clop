import React from 'react';
import { createRoot } from 'react-dom/client';
import { App } from './App';
import { BatchView } from './batch/BatchView';
import { CompareWindow } from './CompareWindow';
import { CropWindow } from './CropWindow';
import { Editor } from './Editor';
import { PreviewWindow } from './PreviewWindow';
import './theme.css';
import './style.css';
import './cards.css';
const query = new URLSearchParams(location.search), crop = query.get('crop'), compare = query.get('compare'), preview = query.get('preview'), batch = query.has('batch');
createRoot(document.getElementById('root')!).render(<React.StrictMode>{batch ? <BatchView/> : crop ? <CropWindow id={crop}/> : compare ? <CompareWindow id={compare}/> : preview ? <PreviewWindow id={preview}/> : query.has('editor') ? <Editor/> : <App/>}</React.StrictMode>);
